let myFriends = [-10,-50,70,100,"90","80",20,30,40,50,60,10];

console.log(myFriends.sort()); //the output will be [-10, -50, 100, 20, 30, 40, 50, 60, 70, 10, "80", "90"] because the sort method sorts the elements in the array as strings by default
console.log(myFriends.reverse()); //the output will be ["90", "80", 10, 70, 60, 50, 40, 30, 20, 100, -50, -10] because the reverse method reverses the order of the elements in the array   
