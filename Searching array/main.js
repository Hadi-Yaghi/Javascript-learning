let myFriends  = ["jad","roy","sara","mohamed","ahmed"];

console.log(myFriends.indexOf("sara")); //the output will be 2 because the indexOf method is case sensitive and it will find the element in the array  


console.log(myFriends.lastIndexOf("sara")); //the output will be 2 because the lastIndexOf method is case sensitive and it will find the element in the array

console.log(myFriends.includes("sara")); //the output will be true because the includes method is case sensitive and it will find the element in the array
